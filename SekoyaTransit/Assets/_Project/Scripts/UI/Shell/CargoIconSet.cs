#nullable enable
using System;
using System.Collections.Generic;
using UnityEngine;
using UnityEngine.UIElements;

namespace SekoyaTransit.UI.Shell
{
    /// <summary>
    /// Resolves the icon shown in front of a cargo name (Issue #182).
    /// </summary>
    public interface ICargoIconSource
    {
        /// <summary>
        /// Returns the icon of <paramref name="cargoId"/>, the generic cargo icon when it has none, or null when no
        /// icon is available at all.
        /// </summary>
        VectorImage? GetIcon(string cargoId);
    }

    /// <summary>
    /// Cargo icons by cargo id, generated by the UI editor bootstrap from <c>Art/Icons/Cargo/&lt;cargo id&gt;.svg</c>
    /// (Issue #182). A cargo without its own file gets the generic icon, so adding a cargo stays data-only.
    /// </summary>
    public sealed class CargoIconSet : ScriptableObject, ICargoIconSource
    {
        [SerializeField]
        private List<Entry> _entries = new List<Entry>();

        [SerializeField]
        private VectorImage? _fallback;

        private Dictionary<string, VectorImage>? _lookup;

        /// <summary>
        /// Gets the generic cargo icon.
        /// </summary>
        public VectorImage? Fallback => _fallback;

        /// <summary>
        /// Gets the cargo ids that have their own icon, in stored order.
        /// </summary>
        public IReadOnlyList<string> CargoIds
        {
            get
            {
                var ids = new string[_entries.Count];
                for (int index = 0; index < _entries.Count; index++)
                {
                    ids[index] = _entries[index].CargoId;
                }

                return ids;
            }
        }

        /// <summary>
        /// Replaces the icons; used by the editor bootstrap.
        /// </summary>
        public void SetIcons(IReadOnlyList<KeyValuePair<string, VectorImage>> icons, VectorImage fallback)
        {
            if (icons is null)
            {
                throw new ArgumentNullException(nameof(icons));
            }

            _fallback = fallback != null ? fallback : throw new ArgumentNullException(nameof(fallback));
            _entries = new List<Entry>(icons.Count);
            for (int index = 0; index < icons.Count; index++)
            {
                KeyValuePair<string, VectorImage> icon = icons[index];
                if (string.IsNullOrWhiteSpace(icon.Key) || icon.Value == null)
                {
                    throw new ArgumentException("Every cargo icon needs a cargo id and an image.", nameof(icons));
                }

                _entries.Add(new Entry(icon.Key, icon.Value));
            }

            _lookup = null;
        }

        /// <summary>
        /// Returns whether <paramref name="cargoId"/> has its own icon (not the generic one).
        /// </summary>
        public bool HasOwnIcon(string cargoId)
        {
            return cargoId != null && GetLookup().ContainsKey(cargoId);
        }

        /// <inheritdoc />
        public VectorImage? GetIcon(string cargoId)
        {
            if (cargoId != null && GetLookup().TryGetValue(cargoId, out VectorImage icon))
            {
                return icon;
            }

            return _fallback;
        }

        private Dictionary<string, VectorImage> GetLookup()
        {
            if (_lookup != null)
            {
                return _lookup;
            }

            _lookup = new Dictionary<string, VectorImage>(StringComparer.Ordinal);
            for (int index = 0; index < _entries.Count; index++)
            {
                Entry entry = _entries[index];
                if (!string.IsNullOrEmpty(entry.CargoId) && entry.Icon != null)
                {
                    _lookup[entry.CargoId] = entry.Icon;
                }
            }

            return _lookup;
        }

        [Serializable]
        private struct Entry
        {
            [SerializeField]
            private string _cargoId;

            [SerializeField]
            private VectorImage _icon;

            public Entry(string cargoId, VectorImage icon)
            {
                _cargoId = cargoId;
                _icon = icon;
            }

            public string CargoId => _cargoId;

            public VectorImage Icon => _icon;
        }
    }
}
